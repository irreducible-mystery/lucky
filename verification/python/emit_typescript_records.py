#!/usr/bin/env python3
"""Emit field records as TypeScript literals typed against the schema encoding.

If any record fails to inhabit the FieldRecord type, `tsc --noEmit` fails.
This makes the TypeScript compiler a second, independent implementation of
the grammar: Python checks via JSON Schema, tsc checks via the type system.
Divergence between the two is itself a finding.
"""
from __future__ import annotations

import json
from pathlib import Path

from fieldlib import front_matter  # date-safe YAML loading

ROOT = Path(__file__).resolve().parents[2]
FIELD = ROOT / "field"
OUT = ROOT / "verification" / "typescript" / "records.generated.ts"



def main() -> None:
    records = [front_matter(p) for p in sorted(FIELD.rglob("*.md"))]
    body = ",\n".join(json.dumps(r, indent=2, default=str) for r in records)
    OUT.write_text(
        "// GENERATED by emit_typescript_records.py — do not edit.\n"
        "// Every record below must inhabit FieldRecord or compilation fails.\n"
        'import type { FieldRecord } from "./schema";\n\n'
        f"export const records: FieldRecord[] = [\n{body}\n];\n"
    )
    print(f"emitted {len(records)} records -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
